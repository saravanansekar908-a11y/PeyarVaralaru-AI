def main():
    json_path = os.path.join(os.path.dirname(__file__), "..", "frontend", "src", "data", "districtsData.json")
    backend_path = os.path.join(os.path.dirname(__file__), "data", "tamil_nadu_38_districts_intelligence.json")

    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    for d in data.get("districts", []):
        no = d.get("no")
        trans = DISTRICT_TRANSLATIONS.get(no)
        if trans:
            d["former_administrative_name_history_ta"] = trans["former_ta"]
            d["ancient_or_historical_name_context_ta"] = trans["ancient_ta"]
            d["change_date_authority_verification_notes_ta"] = trans["change_ta"]
            d["region_ta"] = trans["region_ta"]

        # Timeline localization
        for t in d.get("timeline", []):
            if "title_ta" not in t or not t["title_ta"]:
                t["title_ta"] = t.get("title", "")
            era = t.get("era", "")
            if era == "Administrative Background":
                t["category_ta"] = "முந்தைய நிர்வாக மாவட்டம் / மூல மாவட்டம்"
            elif era == "Historical & Epigraphical Context":
                t["category_ta"] = "பண்டைய குடியேற்றம் / பிராந்தியத் தொடர்பு"
            elif era == "Official Authority & Notes":
                t["category_ta"] = "பெயர் மாற்றத் தேதி / அரசாணை / சரிபார்ப்புக் குறிப்பு"
            else:
                t["category_ta"] = t.get("category", "")
                
            # If description matches former, ancient, or change, use the Tamil version
            if trans:
                desc = t.get("description", "")
                if desc == d.get("former_administrative_name_history"):
                    t["description_ta"] = trans["former_ta"]
                elif desc == d.get("ancient_or_historical_name_context"):
                    t["description_ta"] = trans["ancient_ta"]
                elif desc == d.get("change_date_authority_verification_notes"):
                    t["description_ta"] = trans["change_ta"]

    # Enrich official sources
    for i, s in enumerate(data.get("official_sources", [])):
        if i < len(OFFICIAL_SOURCES_TA):
            s["source_ta"] = OFFICIAL_SOURCES_TA[i]["source_ta"]
            s["use_notes_ta"] = OFFICIAL_SOURCES_TA[i]["use_notes_ta"]

    # Enrich research guidance
    for i, g in enumerate(data.get("research_guidance", [])):
        if i < len(RESEARCH_GUIDANCE_TA):
            g["topic_ta"] = RESEARCH_GUIDANCE_TA[i]["topic_ta"]
            g["guidance_ta"] = RESEARCH_GUIDANCE_TA[i]["guidance_ta"]

    # Save to both frontend and backend files
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    with open(backend_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print("Successfully enriched 38 districts with Tamil translations in both files!")

if __name__ == "__main__":
    main()
